// Generates src/styles/tokens.css from docs/design-system.md (SPEC-21 §7). Run `npm run gen:tokens`
// after any token change, and update the Claude Design artifact in the same change.
//
// Output:
// - colour and label tokens as --<token> on :root (light) and .dark, mapped into Tailwind with
//   `@theme inline` as --color-<token>, so `bg-surface`, `text-ink`, `bg-label-green` work;
// - radius, fonts and typography straight into `@theme` (their names already match Tailwind's
//   namespaces); shadows as runtime variables on :root/.dark, referenced by `@theme inline reference`;
// - spacing as --space-* (a dot becomes _: space-0.5 → --space-0_5) plus --spacing: 4px, so
//   Tailwind's p-2 / gap-6 equal the space-2 / space-6 tokens;
// - fixed sizes as --<token> (use them as h-(--control-h)).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(root, '../docs/design-system.md')
const target = resolve(root, 'src/styles/tokens.css')
const md = readFileSync(source, 'utf8').replace(/\r\n/g, '\n')

/** Rows of the first markdown table after the given heading. */
function table(heading) {
  const start = md.indexOf(heading)
  if (start < 0) throw new Error(`Heading not found: ${heading}`)
  const lines = md.slice(start).split('\n')
  const rows = []
  let inTable = false
  for (const line of lines.slice(1)) {
    if (line.startsWith('|')) {
      inTable = true
      const cells = line
        .split('|')
        .slice(1, -1)
        .map((c) => c.trim())
      if (cells.every((c) => /^:?-+:?$/.test(c))) continue
      rows.push(cells)
    } else if (inTable) break
  }
  return rows.slice(1) // drop the header row
}

const code = (cell) => {
  const m = cell.match(/`([^`]+)`/)
  if (!m) throw new Error(`Expected a code span in "${cell}"`)
  return m[1]
}

const colours = [...table('## 2. Colour tokens'), ...table('### 2.1 Label palette')].map((r) => ({
  name: code(r[0]),
  light: code(r[1]),
  dark: code(r[2]),
}))
const spacing = table('## 4. Spacing').map((r) => ({ name: code(r[0]), value: code(r[1]) }))
const radius = table('## 5. Radius').map((r) => ({ name: code(r[0]), value: code(r[1]) }))
const sizes = table('## 6. Fixed sizes').map((r) => ({ name: code(r[0]), value: code(r[1]) }))
const shadows = table('## 7. Shadows').map((r) => ({ name: code(r[0]), light: code(r[1]), dark: code(r[2]) }))
const type = table('## 3. Typography').map((r) => {
  const [size, line] = r[2].split('/').map((s) => s.trim())
  const weight = r[3].match(/\d{3}/)[0]
  const tracking = r[3].match(/tracking (-?[\d.]+em)/)?.[1]
  return { name: code(r[0]), family: r[1], size, line, weight, tracking }
})
const font = (name) => {
  const m = md.match(new RegExp('`--font-' + name + '`: (.+)'))
  if (!m) throw new Error(`Font --font-${name} not found`)
  return m[1].trim()
}

const varName = (n) => n.replace(/\./g, '_')
const out = []
out.push('/* GENERATED by scripts/gen-tokens.mjs from docs/design-system.md. Do not edit by hand. */')
out.push('')
out.push(':root {')
for (const c of colours) out.push(`  --${c.name}: ${c.light};`)
for (const s of spacing) out.push(`  --${varName(s.name)}: ${s.value};`)
for (const s of sizes) out.push(`  --${s.name}: ${s.value};`)
for (const s of shadows) out.push(`  --${s.name}: ${s.light};`)
out.push('  color-scheme: light;')
out.push('}')
out.push('')
out.push('.dark {')
for (const c of colours) out.push(`  --${c.name}: ${c.dark};`)
for (const s of shadows) out.push(`  --${s.name}: ${s.dark};`)
out.push('  color-scheme: dark;')
out.push('}')
out.push('')
out.push('@theme {')
out.push('  --color-*: initial; /* only design-system colours exist */')
out.push('  --spacing: 4px;')
out.push(`  --font-sans: ${font('sans')};`)
out.push(`  --font-mono: ${font('mono')};`)
for (const r of radius) out.push(`  --${r.name}: ${r.value};`)
for (const t of type) {
  out.push(`  --text-${t.name}: ${t.size};`)
  out.push(`  --text-${t.name}--line-height: ${t.line};`)
  out.push(`  --text-${t.name}--font-weight: ${t.weight};`)
  if (t.tracking) out.push(`  --text-${t.name}--letter-spacing: ${t.tracking};`)
}
out.push('}')
out.push('')
out.push('@theme inline {')
for (const c of colours) out.push(`  --color-${c.name}: var(--${c.name});`)
out.push('}')
out.push('')
// Shadows change per theme, so utilities must read the runtime variable; `reference` stops
// Tailwind from emitting a self-referencing --shadow-* into :root.
out.push('@theme inline reference {')
for (const s of shadows) out.push(`  --${s.name}: var(--${s.name});`)
out.push('}')
out.push('')

writeFileSync(target, out.join('\n'))
console.log(`Wrote ${target}: ${colours.length} colours, ${type.length} type styles.`)
